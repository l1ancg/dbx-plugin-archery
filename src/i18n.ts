export const messages: Record<Locale, Record<string, string>> = {
  "zh-CN": zh,
  en,
};

let current: Locale = "zh-CN";

export function setLocale(locale: string | undefined): void {
  current = (locale ?? "").toLowerCase().startsWith("en") ? "en" : "zh-CN";
}

export function currentLocale(): Locale {
  return current;
}

export function t(key: string, params?: Record<string, string | number>): string {
  const dict = messages[current];
  const template = dict[key] ?? messages["zh-CN"][key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    params[name] === undefined ? `{${name}}` : String(params[name]),
  );
}

export function localizedError(kind: string, detail: string): string {
  const label = t(`error.${kind}`);
  if (!detail) return label;
  return current === "en" ? `${label}: ${detail}` : `${label}：${detail}`;
}
